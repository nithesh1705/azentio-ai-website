import { clsx, type ClassValue } from 'clsx';
import { twMerge } from 'tailwind-merge';

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

export function formatDate(dateStrOrNum: string | number | Date): string {
  try {
    const d = new Date(dateStrOrNum);
    return d.toLocaleDateString('en-US', {
      month: 'short',
      day: 'numeric',
      year: 'numeric',
    });
  } catch {
    return String(dateStrOrNum);
  }
}

export function formatTime(dateStrOrNum: string | number | Date): string {
  try {
    const d = new Date(dateStrOrNum);
    return d.toLocaleTimeString('en-US', {
      hour: '2-digit',
      minute: '2-digit',
    });
  } catch {
    return '';
  }
}

